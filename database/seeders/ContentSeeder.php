                'subtitle' => 'أطقم وشورتات عملية تمتد معك من الإحماء إلى التهدئة.',
                'image' => 'banner-training.webp',
                'link_url' => '/category/training',
                'button_label' => 'تسوّق أطقم التدريب',
                'sort_order' => 2,
            ],
        ];

        foreach ($banners as $banner) {
            $existing = Banner::query()
                ->where('title', $banner['title'])
                ->where('placement', 'home_promo')
                ->first();

            if ($existing !== null) {
                continue;
            }

            Banner::query()->create([
                'title' => $banner['title'],
                'subtitle' => $banner['subtitle'],
                'image_path' => $this->importSeedImage($banner['image'], 'banners'),
                'link_url' => $banner['link_url'],
                'button_label' => $banner['button_label'],
                'placement' => 'home_promo',
                'is_active' => true,
                'sort_order' => $banner['sort_order'],
            ]);
        }
    }

